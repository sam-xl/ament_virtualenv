import argparse
from pathlib import Path
import site
import sys
import sysconfig
from typing import LiteralString, Optional

from ament_index_python import get_package_share_path, PackageNotFoundError
import pytest

USE_AMENT_VIRTUALENV_HELP = (
    'Run the test with the virtual environment generated by ament_virtualenv'
)

USE_AMENT_VIRTUALENV_KEY = pytest.StashKey[bool]()
AMENT_VIRTUALENV_ROOT_KEY = pytest.StashKey[Path]()


@pytest.hookimpl
def pytest_addoption(parser: pytest.Parser):
    """Add options to control the ament_virtualenv_pytest plugin."""
    group = parser.getgroup('ament-virtualenv')
    group.addoption(
        '--use-ament-virtualenv',
        action=argparse.BooleanOptionalAction,
        dest='use_ament_virtualenv',
        help=USE_AMENT_VIRTUALENV_HELP,
    )
    parser.addini(
        'use_ament_virtualenv',
        type='bool',
        help=USE_AMENT_VIRTUALENV_HELP,
    )


def get_setting(
    config: pytest.Config,
    key: LiteralString,
    default=None,
    target_type: Optional[type] = None,
):
    """Get a specific key from the config."""
    value = config.getoption(key)
    if value is not None:
        return value

    ini = config.getini(key)
    if ini is not None and (target_type is None or isinstance(ini, target_type)):
        return ini

    return default


@pytest.hookimpl(tryfirst=True)
def pytest_configure(config: pytest.Config):
    use_ament_virtualenv: Optional[bool] = get_setting(
        config, 'use_ament_virtualenv', target_type=bool,
    )

    # If unspecified, figure it out
    if use_ament_virtualenv is None:
        try:
            package_name = config.getoption('junitprefix', skip=True)
            # FIXME: Add support for non-standard location
            package_share_path = get_package_share_path(package_name, print_warning=False)
            use_ament_virtualenv = (package_share_path/'venv').exists()
        except (PackageNotFoundError, pytest.skip.Exception):
            use_ament_virtualenv = False

    config.stash[USE_AMENT_VIRTUALENV_KEY] = use_ament_virtualenv
    if use_ament_virtualenv:
        package_name = config.getoption('junitprefix', skip=True)
        # FIXME: Add support for non-standard location
        virtualenv_root = get_package_share_path(package_name,
                                                 print_warning=False) / 'venv'

        if not virtualenv_root.exists():
            raise ValueError(f"The virtualenv '{virtualenv_root}' does not exist")

        config.stash[AMENT_VIRTUALENV_ROOT_KEY] = virtualenv_root
        # NOTE: This works, but I'm not 100% sure it is fully correct in all cases
        sitedir = sysconfig.get_path(
            name='purelib',
            scheme='venv',
            vars={'base': str(virtualenv_root)},
        )

        # Reference: https://docs.python.org/3.12/library/venv.html#how-venvs-work
        if sitedir not in sys.path:
            # Inserting entry on the location of the normal venv.
            # The order matters when overriding system packages
            sys.path.insert(len(sys.path)-2, sitedir)
            site.addsitedir(sitedir)
            # NOTE: Manually set the virtualenv prefix and exec_prefix,
            #       to emulate an active virtualenv completely
            sys.prefix = str(virtualenv_root)
            sys.exec_prefix = str(virtualenv_root)


@pytest.hookimpl(tryfirst=True)
def pytest_report_header(config: pytest.Config):
    """Add ament_virtualenv config to pytest header."""
    if config.stash[USE_AMENT_VIRTUALENV_KEY]:
        return [f'ament_virtualenv: {config.stash[AMENT_VIRTUALENV_ROOT_KEY]}']
