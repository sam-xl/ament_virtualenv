from setuptools import find_packages, setup

package_name = 'ament_virtualenv_pytest'

setup(
    name=package_name,
    version='0.0.0',
    packages=find_packages(exclude=['test']),
    data_files=[
        ('share/ament_index/resource_index/packages',
            ['resource/' + package_name]),
        ('share/' + package_name, ['package.xml']),
    ],
    install_requires=['setuptools', 'pytest>=5.0.0'],
    zip_safe=True,
    maintainer='Jasper van Brakel',
    maintainer_email='J.C.vanBrakel@tudelft.nl',
    description='pytest plugin to run tests in environment generated by ament_virtualenv',
    license='Apache-2.0',
    extras_require={
        'test': [
            'pytest',
        ],
    },
    entry_points={
        'pytest11': [
            f'ament_virtualenv = {package_name}.plugin'
        ],
    },
)
